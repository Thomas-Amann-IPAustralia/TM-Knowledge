"""Generate the ontology's status report.

Generated rather than written, for ADR-0042's reason and for the one S009
learned the hard way: a hand-derived analysis over an interlinked set is wrong
on arrival and stale by the next round. Every number below is counted from the
built graph, the shape run and the query run.

It went stale anyway, because the *prose* around the numbers was typed: by
October it still called the ontology "the section 43 draft", said the layer
"authors none of it" and asked an expert to type 52 concepts a machine had typed
a month earlier (the review response, F12). So the prose now states only what
holds by rule, every figure is counted, the report carries no generated-on date,
and `tmk-ontology-report --check` fails CI when the committed file differs from a
rebuild, as `tmk-graph --check` does for `graph/`.

The report is deliberately organised around what the ontology **cannot** do. A
demonstration that lists only its successes is a sales document, and the thing
being demonstrated here is a method whose whole value is that it says what it
does not know.
"""

