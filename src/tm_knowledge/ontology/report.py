_HEADER = """\
<!-- Generated by tm_knowledge.ontology.report. Do not hand-edit: `tmk-ontology-report --check` fails CI when this file differs from a rebuild. -->

# The ontology — what it holds and what it cannot answer

An ontology over the whole Trade Marks Manual of Practice and Procedure, the
Trade Marks Act 1995 and the Trade Marks Regulations 1995, built as a working
demonstrator for a pitch (ADR-0109, ADR-0110). Every figure below is counted
from the built graph, the SHACL run and the query run.

**Two stores, never added together.** `eval/gold/` holds the records a named
expert signed, frozen as the one independent yardstick (ADR-0080). `authored/`
holds what a machine wrote: each record stamped `unreviewed`, with the model or
session that wrote it, the date, and the passages it rests on, quoted (ADR-0079).
No trade marks expert has read the machine-written half; examiners review the
whole at once when it ships (ADR-0120). Nothing in `ontology/draft/` is approved
either: the classes and predicates are a machine-written proposal.

Read section 5 first if you have five minutes. It is the list of things the
ontology cannot do, and it is the honest half of the demonstration.
"""


def _rule_state_lines(rule_set) -> str:
    """One line per rule saying who approved it and when, or what it waits on.

    Generated rather than written, because "neither is approved" was true when
    the paragraph was typed and stopped being true the moment the owner ruled on
    OQ-0004 — and a sentence in a generated report that has to be remembered is
    a sentence that goes stale (ADR-0068).
    """
    lines = []
    for rule in rule_set:
        state = "**approved**" if rule.is_approved else "**pending**"
        lines.append(f"- `{rule.rule_id}` — {state}. {rule.approved_by}")
    return "\n".join(lines)


def _fmt(rows: list[tuple], headers: tuple[str, ...]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(out)


def _names(items, limit: int = 14) -> str:
    items = list(items)
    shown = ", ".join(f"`{item}`" for item in items[:limit])
    return shown + ("…" if len(items) > limit else "") if items else "none"


def render() -> str:
    dataset, build_report = build()
    tbox = load_tbox()
    approved = dataset.graph(APPROVED_GRAPH)
    authored = dataset.graph(AUTHORED_GRAPH)
    source = dataset.graph(SOURCE_GRAPH)

    queries = ask_module.load_queries()
    coverage = ask_module.coverage(dataset, queries)
    rule_set = rules_module.load_rules()
    dataset, rule_counts = rules_module.apply_rules(dataset, rule_set)
    inferred = dataset.graph(INFERRED_GRAPH)
    validation = validate_module.run(dataset)

    predicates = relations_module.collect()
    defined = [usage for usage in predicates if usage.entry is not None]
    unused = [usage.predicate for usage in defined if not usage.count and not usage.authored_count]
    once = [
        usage.predicate for usage in defined if usage.count + usage.authored_count == 1
    ]

    classes = sorted(
        str(node).rsplit("/", 1)[-1]
        for node in tbox.subjects(RDF.type, OWL.Class)
        if str(node).startswith(str(TMK))
    )
    unpopulated = sorted(
        name
        for name in classes
        if not any(
            next(iter(dataset.graph(graph).subjects(RDF.type, TMK[name])), None) is not None
            for graph in NAMED_GRAPHS
        )
    )

    # A concept's hierarchy can come from either store (a correction states its
    # links in the authored graph), so the links are read across both; the
    # concepts are still counted per store.
    def flat(graph) -> list[str]:
        return [
            str(graph.value(node, TMK.goldRecord))
            for node in graph.subjects(RDF.type, TMK.LegalConcept)
            if not any(
                next(iter(g.objects(node, prop)), None) is not None
                for g in (approved, authored)
                for prop in (SKOS.broader, SKOS.narrower)
            )
        ]

    # Every definition is a machine-written record in the authored graph (ADR-0137),
    # whichever store the concept it defines is in; so they are counted as the
    # authored store's, with the signed concepts among them said in words.
    signed_concepts = set(approved.subjects(RDF.type, TMK.LegalConcept))
    definitions = [authored.value(node, TMK.defines) for node in authored.subjects(RDF.type, TMK.Definition)]
    defined_signed = sum(1 for concept in definitions if concept in signed_concepts)

    instruments = sorted(
        (
            str(source.value(node, RDFS.label)),
            source.value(node, TMK.compilationNumber),
            source.value(node, TMK.registerId),
            source.value(node, TMK.compilationStart),
        )
        for node in source.subjects(RDF.type, TMK.Legislation)
    )

    parts = [_HEADER]

    held_lines = "".join(
        f"| {label} | compilation {number} (`{register}`), in force from {_day(start)} |\n"
        for label, number, register, start in instruments
        if number is not None
    )
    parts.append(f"""
| | |
|---|---|
| Pinned snapshot | `{_pin()}` |
{held_lines}| Ontology modules | {len(MODULES)}, all draft |
| Classes declared | {len(classes)} |
| Predicates defined | {len(defined)} in `ontology/predicates.py`; {sum(1 for u in defined if u.count)} used by a signed record, {sum(1 for u in defined if u.authored_count)} by a machine-written one |
| Source graph | {build_report.triples['source']:,} triples over {build_report.chunks} chunks |
| Approved graph | {build_report.triples['approved']:,} triples — signed by a named expert |
| Authored graph | {build_report.triples.get('authored', 0):,} triples — **written by a machine, validated by nobody** |
| Inferred graph | {len(inferred):,} triples — derived by the SPARQL rules, never a signed record |
| SHACL result | {len(validation.by_severity('defect'))} defects, {len(validation.by_severity('gap'))} gaps, {len(validation.by_severity('note'))} notes — exit {validation.exit_code} |
| Competency queries | {len(queries)} of {len(queries) + len(coverage['unqueried']) + len(coverage['deferred'])} questions |
""")

    parts.append("""
## 1. What is in the graph

Four named graphs, and the separation is the governance mechanism (ADR-0007).
`source` restates what upstream already recorded; `approved` restates what a
reviewer signed; `authored` restates what a machine wrote and nobody has read
(ADR-0080); `inferred` holds what the approved rules derive. Nothing is in more
than one, and the SHACL gate checks that each kind of record sits in its own.

**The two record stores are never added together.** A single figure would answer
the question a reader actually has — *how much of this has a person looked at* —
in the one direction that matters, and would do it silently. The table puts the
pair side by side instead.
""")
    signed_current = sum(
        1
        for node in approved.subjects(RDF.type, TMK.ApprovedAssertion)
        if approved.value(node, TMK.assertionPredicate) is not None
        and not _true(approved.value(node, TMK.isCorrected))
    )
    parts.append(_fmt(
        [
            ("concepts", build_report.concepts, build_report.authored.concepts),
            ("concepts sorted into a kind", build_report.concept_types,
             build_report.authored.concept_types),
            ("definitions", 0, f"{len(definitions)} ({defined_signed} of them of signed concepts)"),
            ("relationships, each a direct triple and a reified assertion",
             f"{build_report.relationships} ({signed_current} current, "
             f"{build_report.relationships - signed_current} corrected)",
             build_report.authored.relationships),
            ("corrections to signed records", "—", build_report.authored.corrections),
            ("entity mentions", build_report.mentions, build_report.authored.mentions),
            ("questions (competency, retrieval, search)", build_report.questions,
             build_report.authored.questions),
            ("prohibited uses", build_report.prohibited_uses,
             build_report.authored.prohibited_uses),
        ],
        ("holds", "signed (`approved`)", "machine-written (`authored`)"),
    ))
    parts.append(f"""
A signed record is never edited to correct it. A known defect in one is
corrected by a `GK-` record in `authored/corrections.yaml`, machine-written and
unreviewed, naming the owner's ruling; what serves applies it, and the yardstick
reads the record as signed (ADR-0122). A machine-written concept sorted into a
kind is a typing by a machine; a person has typed none.

The `source` graph holds {build_report.chunks} chunks from {build_report.pages} pages,
{build_report.provisions} provisions and units and {build_report.cases} decisions: the passages
a record rests on and what they cite (ADR-0097), not the whole snapshot.
""")
    if build_report.authored_refused:
        refused = ", ".join(sorted(build_report.authored_refused)[:12])
        parts.append(
            f"\n**{len(build_report.authored_refused)} authored record(s) were "
            "refused** and are in no graph: their envelopes do not validate, so "
            "nothing can say who wrote them or on what. `tmk-harness` names each "
            "one — refused, not dropped, because a silently dropped authored "
            "record is indistinguishable from one that was never written. "
            f"Ids: {refused}.\n"
        )

    parts.append(f"""
### The trust metadata survived

{build_report.citations} citations reached the graph as nodes rather than as bare edges, each
carrying upstream's `extraction` and `certainty` verbatim. That is what makes
CQ-0022 — *did the Manual's authors link that section themselves, or did we work
it out from the wording?* — a query rather than a shrug. Collapsing those two
fields would have destroyed the only thing separating an author's assertion from
an inference, and it cannot be recovered afterwards (CLAUDE.md rule 3).

{build_report.unresolved_citations} of those citations land on nothing this corpus holds. They are recorded
as unresolved, never repaired: CQ-0020 asks for exactly this list.
""")

    shapes = validate_module.load_shapes()
    shape_rows = sorted(
        (str(shapes.value(node, RDFS.label)), _shape_file(node))
        for node in shapes.subjects(RDF.type, SH.NodeShape)
        if shapes.value(node, RDFS.label) is not None
    )
    parts.append("""
## 2. What the shapes stop

`shapes/` runs as the gate before anything publishes, over all four graphs, with
no inference: a shape must not pass because a reasoner supplied the triple the
data was missing. Each shape has a fixture built to violate it, because an
untested shape that never matches anything reads as coverage (`shapes/README.md`).
""")
    parts.append(_fmt(shape_rows, ("shape", "file")))
    notes = Counter(finding.shape for finding in validation.by_severity("note"))
    parts.append(f"""
Two checks run beside the shapes, in `tm_knowledge.ontology.validate`: each kind
of record sits in its own named graph, and SKOS's own integrity conditions hold
(a concept that is both `related` to and a kind of another is a defect when a
machine wrote it, and a note for the owner when it sits inside signed records).

Against the real content: **{len(validation.by_severity('defect'))} defects, {len(validation.by_severity('gap'))} gaps,
{len(validation.by_severity('note'))} notes.** The notes, by shape:

{_fmt(sorted(notes.items()), ("shape", "notes"))}
""")

    contracts = {c.question_id: c for c in ask_module.contracts(dataset, queries)}
    met = sum(1 for c in contracts.values() if c.met)
    lines = ["", "## 3. What it answers", "",
             "One query per competency question that a graph query can answer, named for",
             "the question. Each carries a `limits:` line saying what it has **not**",
             "established — a query that returns rows always looks like an answer. No",
             "query returns a corrected signed record as current.", "",
             "Each is checked against its own signed question record (R06): the rows must",
             "reach the record's required sources, name its expected concepts, and carry the",
             "columns its answer shape needs. **Queries implemented: "
             f"{len(queries)}; contracts met: {met}.** An unmet contract is a gap, not a failure:",
             "it says what the graph cannot yet answer, which a structured test record (A04) or",
             "more relationships would.", ""]
    lines.append(_fmt(
        [(q.question_id, q.answers, contracts[q.question_id].rows if q.question_id in contracts else "—",
          ("met" if contracts[q.question_id].met else "unmet: " + "; ".join(contracts[q.question_id].unmet))
          if q.question_id in contracts else "—")
         for q in queries],
        ("question", "answers", "rows", "contract"),
    ))
    parts.append("\n".join(lines))
    parts.append(f"""
**Modality of the signed relationships still serving, from CQ-0024:**
{_modality_line(approved)}. The blank is not a default and is not filled:
whether a "may" is possibility or permission is a legal reading (guide §5.4).
""")

    approved_rules = [rule for rule in rule_set if rule.is_approved]
    pending_rules = [rule for rule in rule_set if not rule.is_approved]
    parts.append(f"""
## 4. What it infers, and under what conditions

{len(rule_set)} CONSTRUCT rules: **{len(approved_rules)} approved, {len(pending_rules)} pending.**
A person approves every reasoning template before it is relied on. The
`approved-by` line in each file is the approval record, and
`tm_knowledge.ontology.rules` reads it rather than trusting the query — a rule
body may not set its own review status, and an unapproved rule's output is
stamped `reviewStatus "candidate"` and `requiresHumanReview true`. Approved or
not, output goes to the `inferred` graph and nowhere else: approval says an
inference may be relied on, it does not make it a signed record. No OWL
inference is licensed (ADR-0134); these rules are the only reasoning.

{_rule_state_lines(rule_set)}
""")
    parts.append(_fmt(
        [
            (
                rule.rule_id,
                getattr(rule_counts.get(rule.rule_id), "assertions", 0),
                getattr(rule_counts.get(rule.rule_id), "triples", 0),
                rule.basis.split(".")[0][:70],
            )
            for rule in rule_set
        ],
        ("rule", "conclusions", "triples", "stands on"),
    ) + "\n")
    parts.append(
        "**Read the first number, not the second.** *Conclusions* is how many things the "
        "rule concluded; *triples* counts the provenance carried with them. Quoting the "
        "triple count as if it were the number of findings is how the owner came to be "
        "asked to review 71 flagged passages when there were five (Q-44)."
    )

    unmatched = build_report.unmatched_concept_labels
    boundaries = build_report.boundary_concept_labels
    signed_flat, authored_flat = flat(approved), flat(authored)
    act = next((row for row in instruments if row[0] == "Trade Marks Act 1995"), None)
    act_line = (
        f"compilation {act[1]} (`{act[2]}`), in force from {_day(act[3])}"
        if act and act[1] is not None
        else "a compilation this snapshot does not name"
    )
    parts.append(f"""
## 5. What it cannot do — read this part

**Nobody has reviewed the machine-written half.** {build_report.authored.concepts} concepts,
{build_report.authored.relationships} relationships, {build_report.authored.concept_types} typings,
{len(definitions)} definitions and {build_report.authored.corrections} corrections were written by a machine
and are served stamped "Machine · unreviewed". They may be relied on; they are
never approved by being old or unchallenged (ADR-0085). Examiners review the
whole when it ships (ADR-0120). Until then the only independent check on them is
the signed yardstick.

**No concept has a kind a person chose.** {build_report.concept_types} of {build_report.total_concepts} concepts carry a signed
typing; {build_report.authored.concept_types} carry a machine's. Whether a concept is a ground, a test
or a factor is a legal judgement, and every one of these is the agent's.

**Every definition is machine-written.** {len(definitions)} of {build_report.total_concepts} concepts carry one,
{defined_signed} of them signed concepts; the rest have none, because their sources do not
define them. A definition is its own record, never a field on a signed concept,
and approving a label approves no definition (ADR-0137).

**{len(unpopulated)} declared classes hold nothing**: {_names(unpopulated)}.
Some are empty by design (the evidence module: the Manual describes evidence, it
does not hold any); some are the kinds no concept has been sorted into.

**{len(signed_flat)} of {build_report.concepts} signed and {len(authored_flat)} of {build_report.authored.concepts} machine-written concepts sit outside any
hierarchy** — no broader, no narrower. A flat vocabulary connects through its
relationships rather than through "kind of" links.

**{len(unmatched)} competency questions name a concept the vocabulary does not hold**: {_names(unmatched)}.
Either the vocabulary is short a concept, or the question names one by a variant
nobody recorded as a label. **{len(boundaries)} {"names" if len(boundaries) == 1 else "name"} a concept it deliberately excludes**,
which is the opposite of a gap: {_names(boundaries)} (ADR-0075).

**{len(unused)} defined predicates are used by no record**, and {len(once)} by exactly one:
{_names(once)}. A term seen once is a term whose boundaries nobody has tested.

**No OWL profile is claimed and no OWL inference is licensed** (ADR-0134). The
contract is RDF, SKOS, SHACL and the approved SPARQL rules; `owl:` terms are
vocabulary. A predicate names the kinds it joins as annotations the harness
checks (ADR-0131), never as a domain a reasoner would act on.

**One state of the law.** The snapshot holds the Act at {act_line},
and one compilation of the Regulations. An answer names which; it cannot say
what the law was before or has become since. The Manual has no version stamp at
all (Q-05), so point-in-time questions are unanswerable under this snapshot
strategy, and CQ-0014 carries that limitation.

**No decision text exists anywhere in the programme.** "Which cases interpret
this test" is answerable; "what did the court hold" is not (Q-11). PU-0005 is the
output that pretends otherwise.

**The IRIs are names, not addresses.** Every node is named under
`https://data.ipaustralia.gov.au/tmk/` because a Turtle file must name a base.
Nothing is published there and none of the IRIs dereferences; which address the
project may use is OQ-0008, still open. The base is one setting
(`TMK_BASE_IRI`), so changing it is a rebuild, never a find-and-replace.

**{len(coverage['deferred'])} competency questions need a stage that does not exist**: {"; ".join(coverage['deferred']) or "none"}.
A search question is answered by a ranked index and a retrieval question by a
generated answer over retrieved passages; neither is a SPARQL result.
**{len(coverage['unqueried'])} has no query and could have one**: {", ".join(coverage['unqueried']) or "none"}.
""")

    parts.append("""
## 6. What this demonstrates, stated plainly

The claim is not that the ontology is finished or approved. It is that the
method works end to end over the whole Manual, and that the places it breaks are
visible rather than hidden:

1. **A machine can author the ontology without laundering it.** Every
   machine-written record names its author, its date and the passages it rests
   on, quoted, and says it is unreviewed; the signed records stay apart and
   unedited.
2. **The practice/law distinction survives into query output.** Every passage
   is the Manual's practice or the legislation, a shape blocks the attribution
   error the reviewer flagged (PU-0004), and an answer labels each claim's
   authority. The answer-time check on prose is a word heuristic that can miss
   (R08): a clean result is not a verified attribution.
3. **A prohibition became a constraint.** PU-0004 was a paragraph in a YAML
   file; it is now something that stops a publish, with a fixture proving it
   fires and a conforming twin proving it is selective.
4. **The gaps are countable.** Section 5 is produced by the same run that
   produced the successes.
""")
    parts.append(_dependency_section(source))
    return "\n".join(parts).replace("\n\n\n", "\n\n") + "\n"


def _dependency_section(source) -> str:
    """§7: coverage by Part (R10) and what rests on each source (R05), from the
    dependency index over every store, not the approved graph alone."""
    from tm_knowledge.ontology import dependencies
    from tm_knowledge.upstream.loader import load_corpus

    corpus = load_corpus()
    index = dependencies.build(corpus)
    summary = index.summary()
    in_graph = {str(source.value(node, TMK.upstreamRef)) for node in source.subjects(RDF.type, TMK.Chunk)}
    rows = dependencies.coverage_by_part(corpus, index, in_graph)
    table = _fmt([(r["part"], r["title"].removeprefix(r["part"].replace("Part", "Part ")).strip() or "—",
                   r["chunks"], r["in_graph"], r["concepts"], r["relationships"], r["definitions"], r["signed"])
                  for r in rows],
                 ("Part", "title", "chunks", "in the graph", "concepts", "relationships", "definitions",
                  "signed records"))
    empty = [r["part"] for r in rows if not r["in_graph"]]
    unrelated = [r["part"] for r in rows if r["in_graph"] and not r["relationships"]]
    top = sorted(((len(set(index.records(index.touching(ref))) | set(index.records(index.via_manual(ref)))), ref)
                  for ref in corpus.provisions), reverse=True)[:10]
    by = lambda counts: ", ".join(f"{n:,} {k}" for k, n in counts.items())  # noqa: E731
    return f"""
## 7. Coverage by Part, and what rests on each source

Every chunk is searchable (`search.index`), whatever this table says. A chunk is
in the graph when a record names it; the counts are distinct records resting on a
chunk of the Part in the current view (both stores, corrections applied), from the
dependency index (`ontology.dependencies`, R05). A 0 is no recorded record, never
"nothing there". The Manual was captured on {_day(max(p.crawled_at for p in corpus.pages.values())[:10])}; a
compilation of the Act or the Regulations in force after that may not be reflected in it.

{table}

**{len(empty)} Parts have no chunk in the graph**: {", ".join(empty) or "none"}. **{len(unrelated)} more have
no relationship resting on them**: {", ".join(unrelated) or "none"}.

**The dependency index.** {summary['dependencies']:,} dependencies of {summary['records']:,} records on
{summary['refs']:,} refs, current view: by record type {by(summary['by_type'])}; by review
status {by(summary['by_status'])}; by source {by(summary['by_source'])}. Stale (a recorded hash that
no longer matches the pin): {len(summary['stale'])}. A further {summary['history_only']} dependencies are
history only: a signed record named the ref as signed, and a correction removed it or
replaced the record. RULE-0002 is unchanged and is the signed-records-only view of the
same question, from a Manual passage only.

The provisions most rested on, directly or through a Manual passage that cites them:
{", ".join(f"`{ref}` ({n})" for n, ref in top)}.
"""


def _shape_file(node) -> str:
    """The shape file a shape is declared in, by parsing each file alone. Cheap:
    five small files."""
    for name in validate_module.SHAPE_FILES:
        graph = Graph()
        graph.parse(validate_module.SHAPES_DIR / name, format="turtle")
        if (node, RDF.type, SH.NodeShape) in graph:
            return f"`shapes/{name}`"
    return "—"


def _day(value) -> str:
    """`2024-10-14` as "14 October 2024", the form an answer shows."""
    from datetime import date

    day = date.fromisoformat(str(value))
    return f"{day.day} {day:%B %Y}"


def _true(value) -> bool:
    return value is not None and bool(value.toPython())


def _pin() -> str:
    from tm_knowledge.upstream.pin import Pin

    pin = Pin.load()
    return (
        f"{pin.repo} @ {pin.commit[:12]} "
        f"({pin.manual_extractor_version}, {pin.legislation_extractor_version})"
    )


def _modality_line(approved) -> str:
    counts: Counter[str] = Counter()
    for node in approved.subjects(RDF.type, TMK.ApprovedAssertion):
        if approved.value(node, TMK.assertionPredicate) is None:
            continue
        if _true(approved.value(node, TMK.isCorrected)):
            continue  # history, as CQ-0024 reads it (ADR-0122)
        modality = approved.value(node, TMK.modality)
        counts[str(modality) if modality else "not supplied"] += 1
    return ", ".join(f"{count} `{name}`" for name, count in sorted(counts.items()))


def write(text: str | None = None, path: Path | None = None) -> Path:
    path = path or REPORT_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text if text is not None else render(), encoding="utf-8")
    return path


def check(text: str | None = None, path: Path | None = None) -> bool:
    """Whether the committed report is what a rebuild renders.

    A committed generated file that has drifted is worse than one nobody
    committed: it reads as current (ADR-0070's reason, and F12's finding)."""
    path = path or REPORT_PATH
    rendered = text if text is not None else render()
    return path.exists() and path.read_text(encoding="utf-8") == rendered
