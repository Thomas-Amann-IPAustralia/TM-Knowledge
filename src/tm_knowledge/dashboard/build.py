def _markers(value: Any) -> set[str]:
    if isinstance(value, str):
        return set(_MARKER.findall(value))
    if isinstance(value, dict):
        return set().union(*(_markers(item) for item in value.values())) if value else set()
    if isinstance(value, list):
        return set().union(*(_markers(item) for item in value)) if value else set()
    return set()


def check_glossary(pages: dict[str, Any], glossary: dict[str, dict[str, str]]) -> None:
    """A `{{term}}` marker naming a term the glossary does not hold is an error.

    The alternative is a tooltip that silently does not appear, which is how an
    explanation aimed at a reader who needs it quietly stops being offered.
    """
    used = set().union(*(_markers(page) for page in pages.values())) if pages else set()
    missing = sorted(term for term in used if term not in glossary)
    if missing:
        raise BuildError(
            "these glossary markers name terms `docs/GLOSSARY.md` does not define: "
            + ", ".join(missing)
            + ". Add the term there — one glossary, two readers — or drop the marker."
        )


def build(*, generated: str | None = None) -> dict[str, Any]:
    """Every page, keyed by output filename."""
    facts = gather()
    stamp = generated or date.today().isoformat()
    pages = {
        "overview.json": _overview(facts),
        "vocabulary.json": _vocabulary(facts),
        "ontology.json": _ontology(facts),
        "graph.json": _graph_page(facts),
        "questions.json": _questions(facts),
        "limits.json": _limits(facts),
        "decisions.json": _decisions(facts),
        "reports.json": _reports(facts),
        "inbox.json": _inbox(facts),
    }
    check_glossary(pages, facts.glossary)
    pages["glossary.json"] = {"terms": facts.glossary}
    pages["site.json"] = _site(facts, stamp)
    return pages


def _serialise(payload: Any) -> str:
    return json.dumps(payload, indent=1, ensure_ascii=False, sort_keys=False) + "\n"


def write(pages: dict[str, Any] | None = None, out_dir: Path | None = None) -> list[Path]:
    """Write the JSON, and copy the generated reports in beside it."""
    pages = pages if pages is not None else build()
    out_dir = out_dir or DATA_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, payload in pages.items():
        path = out_dir / name
        path.write_text(_serialise(payload), encoding="utf-8")
        written.append(path)

    reports_out = out_dir / "reports"
    reports_out.mkdir(exist_ok=True)
    for name, _, _ in REPORTS:
        source = REPORTS_DIR / name
        if source.exists():
            shutil.copyfile(source, reports_out / name)
            written.append(reports_out / name)
    return written


def check(out_dir: Path | None = None) -> list[str]:
    """Lines describing how the committed data differs from a regeneration.

    The generated-on stamp is excluded — it is the one field that legitimately
    changes without the content changing. Everything else drifting means the
    site is showing a number the repository no longer holds.
    """
    out_dir = out_dir or DATA_DIR
    fresh = build()
    stale: list[str] = []
    for name, payload in fresh.items():
        path = out_dir / name
        if not path.exists():
            stale.append(f"{name}: not generated yet")
            continue
        committed = json.loads(path.read_text(encoding="utf-8"))
        if name == "site.json":
            committed = dict(committed)
            payload = dict(payload)
            committed.pop("generated", None)
            payload.pop("generated", None)
        if committed != payload:
            stale.append(f"{name}: differs from a regeneration")
    return stale
