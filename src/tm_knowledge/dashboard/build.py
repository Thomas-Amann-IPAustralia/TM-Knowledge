# --------------------------------------------------------------------- facts


@dataclass(frozen=True)
class Facts:
    """Everything read off disk, once, before any page is composed."""

    gold: goldset.GoldSet
    modules: dict[str, Graph]
    tbox: Graph
    approved: Graph
    inferred: Graph
    shapes: dict[str, Graph]
    queries: tuple[ask_module.CompetencyQuery, ...]
    rules: tuple[rules_module.Rule, ...]
    pin: dict[str, Any]
    adrs: tuple[sources.Adr, ...]
    stages: tuple[sources.Stage, ...]
    glossary: dict[str, dict[str, str]]
    questions: questions_module.QuestionSet
    rulings: tuple[questions_module.Ruling, ...]


def _read_graph(path: Path) -> Graph:
    if not path.exists():
        raise BuildError(
            f"{path.relative_to(REPO_ROOT)} is missing. The dashboard restates committed "
            f"artefacts; it does not rebuild them. Run `tmk-graph --write --rules` first."
        )
    graph = Graph()
    graph.parse(path, format="turtle")
    return graph


def gather() -> Facts:
    modules = {}
    for path in tbox.module_paths():
        graph = Graph()
        graph.parse(path, format="turtle")
        modules[path.name] = graph

    shapes = {}
    for name in validate.SHAPE_FILES:
        graph = Graph()
        graph.parse(REPO_ROOT / "shapes" / name, format="turtle")
        shapes[name] = graph

    return Facts(
        gold=goldset.load(),
        modules=modules,
        tbox=tbox.load(),
        approved=_read_graph(REPO_ROOT / "graph" / "approved.ttl"),
        inferred=_read_graph(REPO_ROOT / "graph" / "inferred.ttl"),
        shapes=shapes,
        queries=ask_module.load_queries(),
        rules=rules_module.load_rules(),
        pin=json.loads(PIN_PATH.read_text(encoding="utf-8")),
        adrs=sources.read_decisions(),
        stages=sources.read_stage_board(),
        glossary=sources.read_glossary(),
        questions=questions_module.load(),
        rulings=questions_module.load_rulings(),
    )


# ------------------------------------------------------------------- helpers


def _local(term: Any) -> str:
    """The readable tail of an IRI: `tmk:LegalConcept` -> `LegalConcept`."""
    text = str(term)
    if text.startswith(DEFAULT_BASE_IRI + "ref/"):
        return unquote(text[len(DEFAULT_BASE_IRI) + 4 :])
    return re.split(r"[#/]", text.rstrip("/"))[-1]


def _label(graph: Graph, subject: URIRef) -> str:
    value = graph.value(subject, RDFS.label)
    return str(value) if value else _local(subject)


def _comment(graph: Graph, subject: URIRef) -> str:
    value = graph.value(subject, RDFS.comment)
    return " ".join(str(value).split()) if value else ""


def _count(records: Iterable[dict[str, Any]]) -> int:
    return sum(1 for _ in records)


def _band(count: int, low: int, high: int) -> str:
    if count < low:
        return "gap"
    if count > high:
        return "warn"
    return "good"


def _ref_links(refs: Iterable[str]) -> dict[str, Any]:
    return blocks.chips(refs, tone="muted")


def _instances(graph: Graph) -> dict[str, int]:
    """How many things carry each class, in the approved graph."""
    counts: dict[str, int] = {}
    for _, _, cls in graph.triples((None, RDF.type, None)):
        counts[_local(cls)] = counts.get(_local(cls), 0) + 1
    return counts


