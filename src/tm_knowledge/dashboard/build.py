def _shape_rows(facts: Facts) -> list[dict[str, Any]]:
    rows = []
    for name, graph in facts.shapes.items():
        for shape in sorted(graph.subjects(RDF.type, SH.NodeShape)):
            direct = [" ".join(str(value).split()) for value in graph.objects(shape, SH.message)]
            nested = [
                " ".join(str(value).split())
                for prop in graph.objects(shape, SH.property)
                for value in graph.objects(prop, SH.message)
            ]
            sparql = [
                " ".join(str(value).split())
                for constraint in graph.objects(shape, SH.sparql)
                for value in graph.objects(constraint, SH.message)
            ]
            texts = direct + nested + sparql
            rows.append(
                {
                    "shape": _label(graph, shape),
                    "file": f"`shapes/{name}`",
                    "what": texts[0] if texts else "—",
                    "detail": [blocks.listing(texts)] if len(texts) > 1 else [],
                }
            )
    return rows


