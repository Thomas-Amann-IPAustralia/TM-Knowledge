"""Generate the dashboard's data from what the repo already holds.

Every figure on the site is a count of something a reviewer signed or a
generator produced. This module reads **committed artefacts only** — the gold
set, the draft ontology, the two serialised graphs, the queries, the shapes, the
ADR log, the status board, the pin manifest — and never the pinned snapshot. That
line is deliberate and it is what makes the site deployable from a bare checkout:
a page build cannot fail because upstream was unreachable, and it cannot show a
number it did not measure.

The consequence is stated rather than hidden. Figures that live only in the
source graph (216 chunks, 529 citations, 16,405 triples) are **not restated
here**; the site renders `data/derived/reports/ontology.md` instead, which is
produced by the run that has the snapshot. The site restates nothing it can
render.

Output is one JSON file per page under `site/data/`, each in the block
vocabulary of `blocks.py`. `--check` regenerates in memory and diffs against
what is committed, ignoring only the generated-on stamp, so a content change
that was never reflected on the site fails CI rather than going quietly stale.
"""

