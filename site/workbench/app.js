/* The shell: routing, navigation, the glossary tooltip, and the theme.

   Everything it renders comes from `site/data/*.json`, generated by
   `tmk-dashboard --write`. Eight of the nine pages are pure block lists and go
   straight to `blocks.js`; the ninth is the decision form, which owns its own
   module because it is the one page that has state. */

import { renderBlocks } from "./blocks.js";
import { renderInbox } from "./inbox.js";
import { inline, escape } from "./md.js";

const view = document.getElementById("view");
const navEl = document.getElementById("nav");
const tipEl = document.getElementById("tip");
const footEl = document.getElementById("foot");

const cache = new Map();
let site = null;
let glossary = {};

const load = async (name) => {
  if (!cache.has(name)) {
    cache.set(
      name,
      fetch(`data/${name}.json`).then((response) => {
        if (!response.ok) throw new Error(`data/${name}.json — ${response.status}`);
        return response.json();
      })
    );
  }
  return cache.get(name);
};

/* ------------------------------------------------------------------ theme */

const themeButton = document.getElementById("theme");
const applyTheme = (value) => {
  document.documentElement.dataset.theme = value;
  themeButton.textContent = value === "dark" ? "☀" : "◐";
};
const stored = (() => {
  try { return localStorage.getItem("tmk-theme"); } catch { return null; }
})();
applyTheme(stored || (matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light"));
themeButton.addEventListener("click", () => {
  const next = document.documentElement.dataset.theme === "dark" ? "light" : "dark";
  applyTheme(next);
  try { localStorage.setItem("tmk-theme", next); } catch { /* private window */ }
});

/* --------------------------------------------------------------- glossary */

function decorate(root) {
  root.querySelectorAll("button.term").forEach((button) => {
    const entry = glossary[button.dataset.term];
    if (!entry) {
      button.replaceWith(document.createTextNode(button.textContent));
      return;
    }
    button.setAttribute("aria-label", `What ${button.dataset.term} means`);
    const show = () => {
      tipEl.innerHTML =
        `<strong>${escape(entry.term)}</strong>${inline(entry.text)}` +
        `<span class="src">From the project glossary · ${escape(entry.section)}</span>`;
      tipEl.hidden = false;
      const box = button.getBoundingClientRect();
      const tip = tipEl.getBoundingClientRect();
      const left = Math.min(
        Math.max(8, box.left + scrollX),
        scrollX + innerWidth - tip.width - 8
      );
      const above = box.top < tip.height + 16;
      tipEl.style.left = `${left}px`;
      tipEl.style.top = `${above ? box.bottom + scrollY + 8 : box.top + scrollY - tip.height - 8}px`;
    };
    const hide = () => { tipEl.hidden = true; };
    button.addEventListener("mouseenter", show);
    button.addEventListener("focus", show);
    button.addEventListener("mouseleave", hide);
    button.addEventListener("blur", hide);
    button.addEventListener("click", (event) => {
      event.preventDefault();
      tipEl.hidden ? show() : hide();
    });
  });
}
addEventListener("scroll", () => { tipEl.hidden = true; }, { passive: true });

/* ---------------------------------------------------------------- routing */

const parse = () => {
  const raw = location.hash.replace(/^#\/?/, "") || "overview";
  const [id, query] = raw.split("?");
  return { id: id || "overview", params: new URLSearchParams(query || "") };
};

function paintNav(current) {
  navEl.innerHTML = site.nav
    .map((item) => {
      const badge =
        item.id === "inbox" && site.waiting
          ? `<span class="nav-count">${site.waiting}</span>`
          : "";
      return (
        `<a href="#/${item.id}"${item.id === current ? ' aria-current="page"' : ""}>` +
        `${badge}<strong>${escape(item.label)}</strong><small>${escape(item.blurb)}</small></a>`
      );
    })
    .join("");
}

function paintFoot() {
  footEl.innerHTML =
    `<span>Generated ${escape(site.generated)} from the repository.</span>` +
    `<span>Upstream corpus pinned at <code>${escape(site.pin.short)}</code> · ` +
    `${escape(site.pin.manual_version)}, ${escape(site.pin.legislation_version)}.</span>` +
    `<a href="${escape(site.repo)}">The repository</a>`;
  decorate(footEl);
}

async function route() {
  const { id, params } = parse();
  const known = site.nav.some((item) => item.id === id);
  const page = known ? id : "overview";
  paintNav(page);
  navEl.classList.remove("open");
  document.getElementById("menu").setAttribute("aria-expanded", "false");
  view.innerHTML = '<p class="loading">Loading…</p>';

  let data;
  try {
    data = await load(page);
  } catch (error) {
    view.innerHTML =
      `<div class="page-head"><h1>That page did not load</h1>` +
      `<p class="lede">${escape(error.message)}. The site reads generated files from ` +
      `<code>site/data/</code>; if you are running it locally, build them with ` +
      `<code>tmk-dashboard --write</code> and serve the directory over HTTP.</p></div>`;
    return;
  }

  view.innerHTML = "";
  const head = document.createElement("div");
  head.className = "page-head";
  head.innerHTML = `<h1>${escape(data.title)}</h1><p class="lede">${inline(data.lede)}</p>`;
  view.appendChild(head);

  const context = { open: params.get("open"), decorate, site, glossary };
  if (page === "inbox") {
    view.appendChild(renderInbox(data, context));
  } else {
    view.appendChild(renderBlocks(data.blocks, context));
  }
  decorate(view);

  if (!params.get("open")) scrollTo({ top: 0, behavior: "instant" in scrollTo ? "instant" : "auto" });
  document.title = `${data.title} — TM-Knowledge`;
}

/* ------------------------------------------------------------------ start */

document.getElementById("menu").addEventListener("click", (event) => {
  const open = navEl.classList.toggle("open");
  event.currentTarget.setAttribute("aria-expanded", String(open));
});

addEventListener("hashchange", route);

(async () => {
  try {
    [site, glossary] = await Promise.all([
      load("site"),
      load("glossary").then((data) => data.terms),
    ]);
  } catch (error) {
    view.innerHTML =
      `<div class="page-head"><h1>The dashboard data is missing</h1>` +
      `<p class="lede">${escape(error.message)}. Run <code>tmk-dashboard --write</code> and ` +
      `serve this directory over HTTP — opening <code>index.html</code> straight from disk ` +
      `will not work, because the browser blocks the data files.</p></div>`;
    return;
  }
  const waiting = document.getElementById("waiting");
  if (site.waiting) {
    waiting.hidden = false;
    waiting.innerHTML = `<b>${site.waiting}</b><span>waiting on you</span>`;
    waiting.setAttribute("aria-label", `${site.waiting} decisions waiting on you`);
  }
  paintFoot();
  await route();
})();
