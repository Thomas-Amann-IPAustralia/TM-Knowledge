/** A floating tooltip for pictures: one element, moved to the pointer. */
let tipEl = null;
export function tip(html, event) {
  if (!tipEl) { tipEl = document.createElement("div"); tipEl.className = "tip"; tipEl.setAttribute("role", "tooltip"); document.body.appendChild(tipEl); }
  if (!html) { tipEl.classList.remove("on"); return; }
  tipEl.innerHTML = html;
  tipEl.classList.add("on");
  const pad = 14, w = tipEl.offsetWidth, h = tipEl.offsetHeight;
  let x = event.clientX + pad, y = event.clientY + pad;
  if (x + w > innerWidth - 8) x = event.clientX - w - pad;
  if (y + h > innerHeight - 8) y = event.clientY - h - pad;
  tipEl.style.left = `${Math.max(8, x)}px`;
  tipEl.style.top = `${Math.max(8, y)}px`;
}

// ------------------------------------------------------------------ the passage drawer

const drawer = () => document.getElementById("drawer");
let opener = null;

export async function openPassage(ref, { highlight = [], note = "" } = {}) {
  const d = drawer();
  if (!d.classList.contains("open")) opener = document.activeElement;
  d.querySelector(".drawer-title").innerHTML = `<span class="tiny">${esc(ref)}</span><b>Loading…</b>`;
  d.querySelector(".drawer-body").textContent = "";
  d.classList.add("open");
  d.setAttribute("aria-hidden", "false");
  document.getElementById("drawer-veil").classList.add("open");
  d.querySelector(".drawer-close").focus();
  const p = await load("passages");
  const law = p.legislation[ref];
  let title, heading, text, link = "";
  if (law) {
    [, title, heading, text] = law;
    title = `${law[0]} · ${title}`;
  } else {
    const row = p.chunks.find((c) => c[0] === ref);
    if (!row) {
      d.querySelector(".drawer-title").innerHTML = `<b>${esc(ref)}</b>`;
      d.querySelector(".drawer-body").innerHTML = `<p class="tiny">This passage is not in the snapshot the site was built from.</p>`;
      return;
    }
    const page = p.pages[row[1]] || {};
    title = page.title || row[1];
    heading = row[2];
    text = row[3];
    if (page.url) link = `<a href="${esc(page.url)}" target="_blank" rel="noopener">Open this page in the published Manual ↗</a>`;
  }
  let body = esc(text);
  for (const h of highlight.filter((x) => x && x.length > 2).sort((a, b) => b.length - a.length)) {
    const safe = esc(h).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    body = body.replace(new RegExp(`(?<![A-Za-z0-9])(${safe})(?![A-Za-z0-9])`, "gi"), "<mark>$1</mark>");
  }
  d.querySelector(".drawer-title").innerHTML =
    `<div class="row wrap-ok" style="gap:8px">${srcBadge(ref)}<span class="tiny">${esc(ref)}</span></div>` +
    `<b>${esc(title)}</b><span class="tiny">${esc(heading || "")}</span>`;
  d.querySelector(".drawer-body").innerHTML =
    (note ? `<p class="tiny">${note}</p>` : "") + body + (link ? `<p class="tiny" style="margin-top:1.4rem">${link}</p>` : "");
}

function closeDrawer() {
  const d = drawer();
  if (!d.classList.contains("open")) return;
  d.classList.remove("open");
  d.setAttribute("aria-hidden", "true");
  document.getElementById("drawer-veil").classList.remove("open");
  if (opener && document.contains(opener)) opener.focus({ preventScroll: true });
  opener = null;
}

// ------------------------------------------------------------------ router

let cleanup = null;

async function route() {
  let hash = location.hash.replace(/^#\/?/, "");
  let [name, ...rest] = hash.split("/");
  if (ALIASES[name]) {
    const [to, ...extra] = ALIASES[name];
    history.replaceState(null, "", `#/${[to, ...extra, ...rest.filter((r) => /^G[CLP]-/.test(r))].join("/")}`);
    [name, ...rest] = [to, ...extra, ...rest.filter((r) => /^G[CLP]-/.test(r))];
  }
  const known = Object.hasOwn(VIEWS, name);
  const view = known ? VIEWS[name] : home;
  const key = known ? name : "";
  const main = document.getElementById("main");
  if (typeof cleanup === "function") cleanup();
  cleanup = null;
  closeDrawer();
  tip(null);
  const owner = navOwner(key);
  document.querySelectorAll(".nav a").forEach((a) => {
    const on = a.dataset.nav === owner;
    a.classList.toggle("on", on);
    if (on) a.setAttribute("aria-current", "page"); else a.removeAttribute("aria-current");
  });
  document.body.dataset.route = key || "home";
  main.innerHTML = `<p class="loading">Loading…</p>`;
  window.scrollTo(0, 0);
  try {
    const ontology = await load("ontology");
    main.innerHTML = "";
    cleanup = await view.render(main, { ontology, params: rest.map(decodeURIComponent) });
    main.firstElementChild?.classList.add("view-in");
    if (!FULL_SCREEN.has(key)) {
      const next = goDeeper(key);
      if (next) main.insertAdjacentHTML("beforeend", next);
    }
    const build = ontology.build || {};
    document.querySelector(".foot-build").textContent =
      `Built ${build.generated || ""} from the repository and the Manual snapshot ${build.upstream || ""}.`;
  } catch (error) {
    console.error(error);
    main.innerHTML = `<div class="wrap section"><h2>The site's data did not load</h2>
      <p class="muted">${esc(error.message)}</p>
      <p class="muted small">If you are running this locally, generate it first with <code>tmk-explorer --write</code>,
      then serve the <code>site/</code> directory (opening the file directly will not work).</p></div>`;
  }
}

document.addEventListener("click", (event) => {
  const ref = event.target.closest("[data-ref]");
  if (ref) {
    event.preventDefault();
    openPassage(ref.dataset.ref, { highlight: (ref.dataset.hl || "").split("|") });
    return;
  }
  if (event.target.closest(".drawer-close") || event.target.id === "drawer-veil") closeDrawer();
});
document.addEventListener("keydown", (event) => { if (event.key === "Escape") closeDrawer(); });
window.addEventListener("hashchange", route);
initTerms();
route();
