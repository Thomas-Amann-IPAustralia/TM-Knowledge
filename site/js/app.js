/* The examiner explorer: router, data and the pieces every view shares.

   Everything this renders comes from `site/data/*.json`, generated by `tmk-explorer --write`
   from the repository's records and the pinned snapshot. The views arrange those records; they
   never write a legal proposition of their own. Where a record was written by a machine and never
   checked by an expert, the page says so at the point it is shown. A record an expert reviewed is
   marked quietly, never featured (ADR-0130).

   The site leads with outcomes and discloses the ontology last (ADR-0145); since ADR-0148 it does
   so in a new design: outcome pages first (Overview, Research, Explain, Trace a change, What's
   next), then How it works and the Knowledge map, then the standards, glossary and tables. */

