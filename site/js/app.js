export const isLaw = (ref) => /^TM[AR]1995\//.test(ref || "");

/** Which text a ref is from: the Manual, the Act or the Regulations. Each has its own colour and
    mark everywhere on the site: a square, a diamond, a hexagon (ADR-0130). */
export function sourceOf(ref) {
  if ((ref || "").startsWith("TMA1995/")) return "act";
  if ((ref || "").startsWith("TMR1995/")) return "regs";
  return "manual";
}

/** CSS classes for anything drawn from a ref: `manual`, or `law act` / `law regs`. */
export const srcClass = (ref) => (isLaw(ref) ? `law ${sourceOf(ref)}` : "manual");

export const SOURCES = {
  manual: { name: "Trade Marks Manual", short: "Manual", role: "practice" },
  act: { name: "Trade Marks Act 1995", short: "Act", role: "law" },
  regs: { name: "Trade Marks Regulations 1995", short: "Regulations", role: "law" },
};

export function source(ref) {
  const s = SOURCES[sourceOf(ref)];
  return `${s.name} (${s.role})`;
}

const srcLabel = (ref) => { const s = SOURCES[sourceOf(ref)]; return `${s.short} · ${s.role}`; };

export const srcBadge = (ref) => `<span class="src ${srcClass(ref)}"><i class="mark" aria-hidden="true"></i>${srcLabel(ref)}</span>`;

/** A quote, headed by the text it comes from (the label is drawn by the stylesheet). */
export const quoteBlock = (ref, text) => `<blockquote class="quote ${srcClass(ref)}" data-src="${esc(srcLabel(ref))}">${esc(text)}</blockquote>`;

/** The mark of a source as SVG, for pictures: a square, a diamond or a hexagon. */
export function srcShape(src, size = 9) {
  const s = size;
  if (src === "act") return `<path d="M0 ${-s * 1.15} L${s * 1.15} 0 L0 ${s * 1.15} L${-s * 1.15} 0Z"/>`;
  if (src === "regs") return `<path d="M${-s * .55} ${-s} L${s * .55} ${-s} L${s * 1.1} 0 L${s * .55} ${s} L${-s * .55} ${s} L${-s * 1.1} 0Z"/>`;
  return `<rect x="${-s * .85}" y="${-s * .85}" width="${s * 1.7}" height="${s * 1.7}" rx="2"/>`;
}

/** A short, readable name for a ref, from the ref itself (no lookup needed). */
export function refLabel(ref) {
  ref = String(ref || "");
  let m = ref.match(/^TM([AR])1995\/([a-z]+)([^/]*)(?:\/(.+))?$/);
  if (m) {
    const inst = m[1] === "A" ? "Act" : "Regs";
    const unit = m[2] === "s" ? "s" : m[2] === "r" ? "r" : m[2];
    const def = m[4] ? ` (${m[4].replace(/-/g, " ")})` : "";
    return `${inst} ${unit} ${m[3]}${def}`;
  }
  m = ref.match(/^TMM\/Part([0-9]+[A-Za-z]*)(.*)$/);
  if (m) {
    const rest = m[2].replace(/^\//, "").replace(/#.*$/, "").replace(/~\d+$/, "");
    const words = (slug) => {
      const w = slug.replace(/-+/g, " ").replace(/\s+/g, " ").trim().replace(/\d+$/, "").trim();
      const cut = w.length > 34 ? `${w.slice(0, 33).replace(/\s+\S*$/, "")}…` : w;
      return cut.charAt(0).toUpperCase() + cut.slice(1);
    };
    const named = /x-([a-z0-9-]+)/.exec(rest);
    if (named) return `Pt ${m[1]} · ${words(named[1])}`;
    const segs = rest.split("/").filter(Boolean);
    // "2-3-1-a-variety-names" is section 2.3.1(a), headed "Variety names"
    const slug = /^(\d+(?:-\d+)*)(?:-([a-z]))?-([a-z].*)$/.exec(segs[segs.length - 1] || "");
    if (slug) return `Pt ${m[1]} · ${slug[1].replace(/-/g, ".")}${slug[2] ? `(${slug[2]})` : ""} ${words(slug[3])}`;
    const tail = segs.filter((x, i, a) => !(i > 0 && a[i - 1] === x)).join(".");
    return `Pt ${m[1]}${tail ? " · " + tail : ""}`;
  }
  return ref;
}

export function refChip(ref, extra = "") {
  return `<button type="button" class="ref ${srcClass(ref)}" data-ref="${esc(ref)}" title="${esc(source(ref))}: ${esc(ref)}"${extra}><i class="mark" aria-hidden="true"></i>${esc(refLabel(ref))}</button>`;
}

/** Who wrote a record. A machine-written one always says so (rule 8); one an expert reviewed
    says so quietly, and is never singled out (ADR-0130). */
export function trustBadge(origin) {
  return origin === "signed"
    ? `<span class="trust reviewed" title="A trade marks expert has reviewed this record">Reviewed</span>`
    : `<span class="trust machine" title="Written by a machine; no expert has reviewed it">Machine · unreviewed</span>`;
}

/** A state, said in words as well as colour. */
export const statePill = (state, label) => `<span class="pill ${esc(state)}">${esc(label)}</span>`;

/** The condition and the hedge a connection's sentence states it under, in its own words
    (review response F14; the hedge split from the condition in S041, R01). Shown beside the
    connection so it never reads as more than its sentence says. */
export function qualifiedLine(r) {
  // A sentence with a conditional word nobody has assessed says so (R07): absent a condition,
  // it may still hold only in some cases.
  const unknown = r.condition === "not_assessed"
    ? `<p class="tiny">Its sentence has a conditional word (if, where, unless, when, except) that no one has assessed yet.</p>` : "";
  if (!r.when && !r.hedge) return unknown;
  const parts = [r.when ? `only when “${esc(r.when)}”` : "", r.hedge ? `stated as “${esc(r.hedge)}”` : ""].filter(Boolean);
  return `<p class="small"><b>Only as the source qualifies it:</b> ${parts.join("; ")}</p>`;
}

/** A concept's definition: its own machine-written record (ADR-0137), stamped as such, and
    saying where its words come from, so the Act's words and the Manual's practice are never
    read as one another (CLAUDE.md rule 5). */
export function definitionBlock(d) {
  if (!d) return "";
  const src = sourceOf(d.ref) === "act" ? "the Act" : sourceOf(d.ref) === "regs" ? "the Regulations" : "the Manual";
  const own = src === "the Regulations" ? "the Regulations'" : `${src}'s`;
  const whose = d.basis === "statutory_definition" ? `${own} own definition, quoted`
    : d.basis === "statutory_provision" ? `written from ${src}` : "written from the Manual, which states practice, not law";
  return `<div class="def-block">
    <h4>Definition <span class="trust machine" title="Written by a machine; no expert has reviewed it">Machine · unreviewed</span></h4>
    <p>${esc(d.text)}</p>
    ${d.scope_note ? `<p class="tiny"><span class="muted">Scope:</span> ${esc(d.scope_note)}</p>` : ""}
    <p class="tiny">${esc(whose)} ${refChip(d.ref)}</p></div>`;
}

/** The "is a kind of" links a concept record states in its own fields, which no connection
    carries (tmk-explorer works them out). They rest on the record that states them, not on a
    sentence, and say so. `link(id)` renders the other idea. */
export function hierarchyBlock(x, link) {
  const h = x.hierarchy;
  if (!h) return "";
  const line = (label, items) => items.length
    ? `<p class="small"><span class="muted">${label}</span> ${items.map((i) => `${link(i.id)} ${trustBadge(i.origin)}`).join(" · ")}</p>` : "";
  const records = [...new Set([...h.kind_of, ...h.kinds].flatMap((i) => i.records))].sort();
  return `<h4>Hierarchy on the record</h4>
    ${line("A kind of", h.kind_of)}${line("Kinds of it", h.kinds)}
    <p class="tiny">Stated in the record${records.length === 1 ? "" : "s"} of ${records.map(esc).join(", ")}, not as a connection, so no sentence is cited for it.</p>`;
}

/** Where a structured legal test or process template is set out (the table view). */
export const structureHref = (id) => `#/table/${String(id).startsWith("GP-") ? "processes" : "tests"}/${encodeURIComponent(id)}`;

/** The structured legal tests and process templates that name an idea (Package 4, ADR-0142).
    Each is a machine-written record of its own, listed with its stamp and a link to the table that
    sets it out; tmk-explorer works out which name the idea. */
export function structuresBlock(x, ontology) {
  const all = [...(ontology.structures?.tests || []), ...(ontology.structures?.processes || [])];
  const items = (x.structures || []).map((id) => all.find((r) => r.id === id)).filter(Boolean);
  if (!items.length) return "";
  return `<h4>In a structured test or procedure</h4>
    <ul class="struct-links">${items.map((r) => `<li><a href="${structureHref(r.id)}">${esc(r.title)}</a> ${trustBadge(r.origin)}</li>`).join("")}</ul>`;
}

