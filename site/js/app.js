// ------------------------------------------------------------------ the passage drawer

const drawer = () => document.getElementById("drawer");

export async function openPassage(ref, { highlight = [], note = "" } = {}) {
  const d = drawer();
  d.querySelector(".drawer-title").innerHTML = `<span class="tiny">${esc(ref)}</span><b>Loading…</b>`;
  d.querySelector(".drawer-body").textContent = "";
  d.classList.add("open");
  d.setAttribute("aria-hidden", "false");
  const p = await load("passages");
  const law = p.legislation[ref];
  let title, heading, text, link = "";
  if (law) {
    [, title, heading, text] = law;
    title = `${law[0]} · ${title}`;
  } else {
    const row = p.chunks.find((c) => c[0] === ref);
    if (!row) {
      d.querySelector(".drawer-title").innerHTML = `<b>${esc(ref)}</b>`;
      d.querySelector(".drawer-body").innerHTML = `<p class="tiny">This passage is not in the snapshot the site was built from.</p>`;
      return;
    }
    const page = p.pages[row[1]] || {};
    title = page.title || row[1];
    heading = row[2];
    text = row[3];
    if (page.url) link = `<a href="${esc(page.url)}" target="_blank" rel="noopener">Open this page in the published Manual ↗</a>`;
  }
  let body = esc(text);
  for (const h of highlight.filter((x) => x && x.length > 2).sort((a, b) => b.length - a.length)) {
    const safe = esc(h).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    body = body.replace(new RegExp(`(?<![A-Za-z0-9])(${safe})(?![A-Za-z0-9])`, "gi"), "<mark>$1</mark>");
  }
  d.querySelector(".drawer-title").innerHTML =
    `<div style="display:flex;gap:.4rem;align-items:center;flex-wrap:wrap">${srcBadge(ref)}<span class="tiny">${esc(ref)}</span></div>` +
    `<b>${esc(title)}</b><span class="tiny">${esc(heading || "")}</span>`;
  d.querySelector(".drawer-body").innerHTML =
    (note ? `<p class="tiny">${note}</p>` : "") + body + (link ? `<p class="tiny" style="margin-top:1.2rem">${link}</p>` : "");
  d.querySelector(".drawer-close").focus();
}

function closeDrawer() {
  drawer().classList.remove("open");
  drawer().setAttribute("aria-hidden", "true");
}

// ------------------------------------------------------------------ router

let cleanup = null;

async function route() {
  const hash = location.hash.replace(/^#\/?/, "");
  const [name, ...rest] = hash.split("/");
  const view = VIEWS[name] || home;
  const main = document.getElementById("main");
  if (typeof cleanup === "function") cleanup();
  cleanup = null;
  closeDrawer();
  document.querySelectorAll(".nav a").forEach((a) => a.classList.toggle("on", a.dataset.route === name));
  main.innerHTML = `<p class="loading">Loading…</p>`;
  try {
    const ontology = await load("ontology");
    main.innerHTML = "";
    cleanup = await view.render(main, { ontology, params: rest.map(decodeURIComponent) });
    const build = ontology.build || {};
    document.querySelector(".foot-build").textContent =
      `Built ${build.generated || ""} from the repository and the Manual snapshot ${build.upstream || ""}.`;
  } catch (error) {
    console.error(error);
    main.innerHTML = `<div class="wrap"><h2>The map's data did not load</h2>
      <p class="muted">${esc(error.message)}</p>
      <p class="muted small">If you are running this locally, generate it first with <code>tmk-explorer --write</code>,
      then serve the <code>site/</code> directory (opening the file directly will not work).</p></div>`;
  }
  if (!rest.length) window.scrollTo(0, 0);
}

function theme() {
  const root = document.documentElement;
  try { const saved = localStorage.getItem("tmk-theme"); if (saved) root.dataset.theme = saved; } catch { /* storage blocked */ }
  document.querySelector(".theme").addEventListener("click", () => {
    const dark = root.dataset.theme ? root.dataset.theme === "dark" : matchMedia("(prefers-color-scheme: dark)").matches;
    root.dataset.theme = dark ? "light" : "dark";
    try { localStorage.setItem("tmk-theme", root.dataset.theme); } catch { /* storage blocked */ }
    window.dispatchEvent(new Event("tmk-theme"));
  });
}

document.addEventListener("click", (event) => {
  const ref = event.target.closest("[data-ref]");
  if (ref) {
    event.preventDefault();
    openPassage(ref.dataset.ref, { highlight: (ref.dataset.hl || "").split("|") });
    return;
  }
  if (event.target.closest(".drawer-close")) closeDrawer();
});
document.addEventListener("keydown", (event) => { if (event.key === "Escape") closeDrawer(); });
window.addEventListener("hashchange", route);
theme();
route();
